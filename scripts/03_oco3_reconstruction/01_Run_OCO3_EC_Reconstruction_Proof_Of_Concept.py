def verdict_table(overall: pd.DataFrame, identity: pd.DataFrame, benefit: pd.DataFrame) -> dict[str, str]:
    grouped = overall[overall["validation"] == "grouped_artificial_gap"].copy()
    def rmse(model: str, validation: str = "grouped_artificial_gap") -> float:
        row = overall[(overall["validation"] == validation) & (overall["model"] == model)]
        return float(row["RMSE"].iloc[0]) if not row.empty else np.nan

    partial = rmse("Partial_observation_baseline")
    gosif = rmse("GOSIF_raw_baseline")
    best = best_model_name(overall)
    best_rmse = rmse(best)
    spatial = rmse(best, "spatial_site_held_out")
    temporal = rmse(best, "incremental_temporal")
    stress = rmse(best, "spatial_temporal_stress")
    recon_help = "GREEN" if math.isfinite(partial) and math.isfinite(best_rmse) and best_rmse < partial * 0.95 else ("YELLOW" if math.isfinite(partial) and math.isfinite(best_rmse) and best_rmse < partial else "RED")
    gosif_help = "GREEN" if math.isfinite(gosif) and math.isfinite(best_rmse) and best_rmse < gosif * 0.95 else ("YELLOW" if math.isfinite(gosif) and math.isfinite(best_rmse) and best_rmse < gosif else "RED")
    spatial_ok = "GREEN" if math.isfinite(spatial) and math.isfinite(partial) and spatial < partial else ("YELLOW" if math.isfinite(spatial) else "RED")
    temporal_ok = "GREEN" if math.isfinite(temporal) and math.isfinite(partial) and temporal < partial else ("YELLOW" if math.isfinite(temporal) else "RED")
    no_collapse = "GREEN"
    if not identity.empty and identity["target_sensor_identity_dilution_risk"].astype(str).eq("YES").any():
        no_collapse = "YELLOW"
    final = "GO" if recon_help in {"GREEN", "YELLOW"} and gosif_help in {"GREEN", "YELLOW"} and spatial_ok != "RED" and temporal_ok != "RED" and no_collapse != "RED" else "NO-GO"
    return {
        "Can missing OCO-3 SIF be reconstructed?": recon_help,
        "Does target + GOSIF beat partial OCO-3?": recon_help,
        "Does target + GOSIF beat GOSIF alone?": gosif_help,
        "Does it preserve target-sensor identity?": no_collapse,
        "Does it generalize spatially?": spatial_ok,
        "Does it generalize temporally?": temporal_ok,
        "Safe to reconstruct real incomplete OCO-3 data?": final,
    }


def make_readme(
    gap: pd.DataFrame,
    truth: pd.DataFrame,
    overall: pd.DataFrame,
    best_model: str,
    verdicts: dict[str, str],
) -> Path:
    path = OUTPUT_ROOT / "OCO3_Reconstruction_READ_ME_FIRST.txt"
    def metric(model: str, validation: str, metric_name: str) -> float:
        row = overall[(overall["model"] == model) & (overall["validation"] == validation)]
        return float(row[metric_name].iloc[0]) if not row.empty else np.nan
    partial_rmse = metric("Partial_observation_baseline", "grouped_artificial_gap", "RMSE")
    gosif_rmse = metric("GOSIF_raw_baseline", "grouped_artificial_gap", "RMSE")
    best_rmse = metric(best_model, "grouped_artificial_gap", "RMSE")
    spatial_rmse = metric(best_model, "spatial_site_held_out", "RMSE")
    temporal_rmse = metric(best_model, "incremental_temporal", "RMSE")
    improvement = (partial_rmse - best_rmse) / partial_rmse * 100 if math.isfinite(partial_rmse) and partial_rmse else np.nan
    text = f"""OCO-3 EC-footprint reconstruction proof-of-concept

1. What did we test?
We tested whether artificially missing OCO-3 EC-footprint SIF can be recovered as one EC-footprint representative SIF value. Whole real OCO-3 source footprints were removed; no fine raster cells were randomly deleted.

2. How many original complete OCO-3 cases did we use?
Complete OCO-3 + usable GOSIF cases used: {truth['original_case_ID'].nunique():,}.
Artificial-gap samples created: {len(gap):,}.

3. How did we simulate missing coverage?
For each complete case, the script removed whole OCO-3 footprint polygons to approximate fixed coverage levels and empirical real-OCO3-like coverage levels.

4. Which model performed best?
Best grouped artificial-gap model: {best_model}.

5. Did reconstruction beat simply using partial OCO-3?
Partial OCO-3 RMSE = {partial_rmse:.4f}.
Best reconstruction RMSE = {best_rmse:.4f}.
Improvement over partial observation = {improvement:.1f}%.

6. Did adding GOSIF help?
Raw GOSIF RMSE = {gosif_rmse:.4f}. Target + GOSIF result is shown by the best-model RMSE above.

7. Did it work at unseen sites?
Best-model spatial held-out-site RMSE = {spatial_rmse:.4f}.

8. Did it work in future temporal folds?
Best-model incremental temporal RMSE = {temporal_rmse:.4f}.

9. Did performance get worse as coverage decreased?
See OCO3_Model_Performance_By_Coverage.csv and Figure 2. Low-coverage performance is evaluated separately.

10. Final decision:
{verdicts.get('Safe to reconstruct real incomplete OCO-3 data?', 'NO-GO')}
"""
