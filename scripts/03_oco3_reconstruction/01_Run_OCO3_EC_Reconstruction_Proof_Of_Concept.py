def grouped_kfold_splits(frame: pd.DataFrame, group_col: str, n_splits: int = 5) -> list[tuple[str, np.ndarray, np.ndarray]]:
    groups = frame[group_col].astype(str).to_numpy()
    n_unique = len(np.unique(groups))
    if n_unique < 2:
        return []
    folds = GroupKFold(n_splits=min(n_splits, n_unique))
    return [(f"{group_col}_fold_{i}", train_idx, test_idx) for i, (train_idx, test_idx) in enumerate(folds.split(frame, groups=groups), start=1)]


def temporal_splits(frame: pd.DataFrame) -> list[tuple[str, np.ndarray, np.ndarray]]:
    out: list[tuple[str, np.ndarray, np.ndarray]] = []
    years = sorted(int(y) for y in pd.to_numeric(frame["year"], errors="coerce").dropna().unique())
    for year in years[:-1]:
        train_idx = frame.index[frame["year"].astype(int) <= year].to_numpy()
        test_idx = frame.index[frame["year"].astype(int) == year + 1].to_numpy()
        if len(train_idx) >= 40 and len(test_idx) >= 10:
            out.append((f"train_through_{year}_test_{year+1}", train_idx, test_idx))
    return out


def spatial_temporal_stress_splits(frame: pd.DataFrame) -> list[tuple[str, np.ndarray, np.ndarray]]:
    out: list[tuple[str, np.ndarray, np.ndarray]] = []
    years = sorted(int(y) for y in pd.to_numeric(frame["year"], errors="coerce").dropna().unique())
    for year in years[:-1]:
        future = frame[frame["year"].astype(int) == year + 1]
        if future["SITE_ID"].nunique() < 4:
            continue
        sites = sorted(future["SITE_ID"].astype(str).unique())
        rng = np.random.default_rng(stable_seed("stress", year, RANDOM_SEED))
        rng.shuffle(sites)
        held_sites = set(sites[: max(2, int(round(len(sites) * 0.25)))])
        train_mask = (frame["year"].astype(int) <= year) & (~frame["SITE_ID"].astype(str).isin(held_sites))
        test_mask = (frame["year"].astype(int) == year + 1) & (frame["SITE_ID"].astype(str).isin(held_sites))
        train_idx = frame.index[train_mask].to_numpy()
        test_idx = frame.index[test_mask].to_numpy()
        if len(train_idx) >= 40 and len(test_idx) >= 10:
            out.append((f"stress_train_to_{year}_held_sites_test_{year+1}", train_idx, test_idx))
    return out


def evaluate_validation(frame: pd.DataFrame, validation_name: str, splits: list[tuple[str, np.ndarray, np.ndarray]]) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    all_pred_rows: list[dict[str, Any]] = []
    params_rows: list[dict[str, Any]] = []
    fold_perf_rows: list[dict[str, Any]] = []
    for fold_id, train_idx, test_idx in splits:
        train = frame.loc[train_idx].copy()
        test = frame.loc[test_idx].copy()
        print(f"Validation {validation_name} {fold_id}: train={len(train)}, test={len(test)}")
        pred_rows = fold_predictions(train, test, validation_name, fold_id, params_rows)
        all_pred_rows.extend(pred_rows)
        fold_pred = pd.DataFrame(pred_rows)
        for model, group in fold_pred.groupby("model"):
            metrics = metrics_dict(
                group["true_complete_OCO3_EC_SIF"].astype(float).to_numpy(),
                group["prediction"].astype(float).to_numpy(),
            )
            metrics.update({"validation": validation_name, "fold_id": fold_id, "model": model})
            fold_perf_rows.append(metrics)
    return pd.DataFrame(all_pred_rows), pd.DataFrame(fold_perf_rows), pd.DataFrame(params_rows)


def summarize_predictions(predictions: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    overall_rows: list[dict[str, Any]] = []
    coverage_rows: list[dict[str, Any]] = []
    if predictions.empty:
        return pd.DataFrame(), pd.DataFrame()
    for (validation, model), group in predictions.groupby(["validation", "model"]):
        metrics = metrics_dict(group["true_complete_OCO3_EC_SIF"].astype(float).to_numpy(), group["prediction"].astype(float).to_numpy())
        metrics.update({"validation": validation, "model": model})
        overall_rows.append(metrics)
