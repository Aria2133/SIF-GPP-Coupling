def native(path: Path | str) -> str:
    return os.fspath(path)


def ensure_dirs() -> None:
    for path in [OUTPUT_ROOT, FIGURE_ROOT, QC_ROOT]:
        path.mkdir(parents=True, exist_ok=True)


def split_compact_paths(value: Any) -> list[str]:
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return []
    return [part.strip() for part in str(value).split("|") if part.strip()]


def norm_path(value: str | Path) -> str:
    return str(Path(value)).lower()


def file_state(path: Path) -> dict[str, Any]:
    try:
        stat = path.stat()
        return {
            "path": str(path),
            "exists": True,
            "size_bytes": int(stat.st_size),
            "mtime_ns": int(stat.st_mtime_ns),
        }
    except Exception as exc:
        return {
            "path": str(path),
            "exists": False,
            "size_bytes": np.nan,
            "mtime_ns": np.nan,
            "error": f"{type(exc).__name__}: {exc}",
        }


def stable_seed(*parts: Any) -> int:
    text = "|".join(str(part) for part in parts)
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
    return int(digest, 16) % (2**32 - 1)


def safe_float(value: Any, default: float = np.nan) -> float:
    try:
        out = float(value)
        return out if math.isfinite(out) else default
    except Exception:
        return default


def coverage_class(value: float) -> str:
    if not math.isfinite(value):
        return "NaN"
    if value <= 0.10:
        return "0-0.10"
    if value <= 0.25:
        return ">0.10-0.25"
    if value <= 0.50:
        return ">0.25-0.50"
    if value <= 0.75:
        return ">0.50-0.75"
    if value <= 0.90:
        return ">0.75-0.90"
    if value < 1.00:
        return ">0.90-<1.00"
    return "1.00"


