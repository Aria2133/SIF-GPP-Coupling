def validate_source_modification(before: pd.DataFrame) -> pd.DataFrame:
    after_rows = []
    for path in before["path"].astype(str):
        state = file_state(Path(path))
        after_rows.append(state)
    after = pd.DataFrame(after_rows).rename(columns={"size_bytes": "size_bytes_after", "mtime_ns": "mtime_ns_after", "exists": "exists_after"})
    before2 = before.rename(columns={"size_bytes": "size_bytes_before", "mtime_ns": "mtime_ns_before", "exists": "exists_before"})
    merged = before2.merge(after[["path", "exists_after", "size_bytes_after", "mtime_ns_after"]], on="path", how="left")
    merged["unchanged_size_and_mtime"] = (
        (merged["exists_before"] == merged["exists_after"])
        & (merged["size_bytes_before"] == merged["size_bytes_after"])
        & (merged["mtime_ns_before"] == merged["mtime_ns_after"])
    )
    return merged


