@dataclass
class FootprintRecord:
    footprint_id: str
    source_file: str
    source_index: int
    sif_value: float
    ec_flat_indices: np.ndarray
    n_ec_cells: int
    single_probability_sum: float


def build_case_context(row: pd.Series) -> dict[str, Any]:
    gpp_path = Path(str(row["matching_gpp_tif"]))
    with rasterio.open(native(gpp_path)) as ds:
        prob = ds.read(1).astype(np.float64)
        blind = ds.read(3).astype(np.float64)
        template = {
            "gpp_tif": str(gpp_path),
            "height": int(ds.height),
            "width": int(ds.width),
            "_crs_obj": ds.crs,
            "_transform_obj": ds.transform,
            "_bounds_tuple": tuple(ds.bounds),
        }
    ec_mask = np.isfinite(prob) & (prob > 0)
    blind_mask = np.isfinite(blind) & (blind == 1)
    transformer = Transformer.from_crs(CRS.from_epsg(4326), template["_crs_obj"], always_xy=True)
    geographic_bounds = footprint.template_geographic_bounds(template)
    return {
        "row": row,
        "template": template,
        "probability": prob,
        "probability_flat": prob.ravel(),
        "ec_mask": ec_mask,
        "blind_mask": blind_mask,
        "ec_flat_indices": np.flatnonzero(ec_mask.ravel()),
        "probability_sum_full_EC": float(prob[ec_mask].sum(dtype=np.float64)),
        "n_EC_pixels": int(ec_mask.sum()),
        "geographic_bounds": geographic_bounds,
        "geographic_cell_keys": footprint.bounds_to_cell_keys(geographic_bounds),
        "transformer": transformer,
        "footprints": [],
        "candidate_count": 0,
        "bad_geometry_count": 0,
        "no_spatial_intersection_count": 0,
        "geometry_fields_used": set(),
        "source_files_used": set(),
    }


def append_footprints_from_source_to_contexts(
    source: dict[str, Any],
    contexts: list[dict[str, Any]],
    missing_geometry_rows: list[dict[str, Any]],
) -> str:
    if not contexts:
        return "NO_CONTEXTS"

    context_keys: dict[int, list[dict[str, Any]]] = defaultdict(list)
    target_keys: set[int] = set()
    for context in contexts:
        for key in context["geographic_cell_keys"]:
            context_keys[key].append(context)
            target_keys.add(key)
    if not target_keys:
        return "NO_TARGET_CELLS"

    file_path = Path(str(source["file_path"]))
    try:
        with h5py.File(base.native_path(file_path), "r") as handle:
            sif_path = str(source.get("detected_sif_variable", ""))
            if not sif_path or sif_path not in handle:
                return "MISSING_SIF_VARIABLE"
            geom_lat_path, geom_lon_path, detection_method = footprint.detect_footprint_geometry_pair(handle, source)
            if not geom_lat_path or not geom_lon_path:
                missing_geometry_rows.append(
                    {
                        "PRODUCT": "OCO-3",
                        "file_path": str(file_path),
                        "YYYYMM": source.get("detected_YYYYMM", ""),
                        "detected_sif_variable": sif_path,
                        "detected_lat_variable": source.get("detected_lat_variable", ""),
                        "detected_lon_variable": source.get("detected_lon_variable", ""),
                        "missing_footprint_geometry_reason": "No usable OCO-3 footprint/corner geometry pair detected.",
                        "available_geometry_hint": detection_method,
                    }
                )
                return "PRODUCT_LACKS_FOOTPRINT_GEOMETRY"
            n_observations = int(handle[sif_path].shape[0])
            sif_values = base.dataset_chunk_values(handle[sif_path], 0, n_observations, "mean")
            lat_vertices = footprint.vertices_as_observation_rows(
                footprint.numeric_dataset_array(handle[geom_lat_path]),
                n_observations,
            )
            lon_vertices = footprint.vertices_as_observation_rows(
                footprint.numeric_dataset_array(handle[geom_lon_path]),
                n_observations,
            )
            lat_vertices, lon_vertices = footprint.bounds_rows_to_four_vertices(lat_vertices, lon_vertices)
            lon_vertices = footprint.normalize_longitudes(lon_vertices)
    except Exception as exc:
        return f"FAILED_SOURCE_READ:{type(exc).__name__}:{exc}"

    valid_sif = np.isfinite(sif_values) & (sif_values > -9000)
    finite_vertices = np.isfinite(lat_vertices).all(axis=1) & np.isfinite(lon_vertices).all(axis=1)
    lon_min = np.full(lon_vertices.shape[0], np.nan, dtype=np.float64)
    lon_max = np.full(lon_vertices.shape[0], np.nan, dtype=np.float64)
    lat_min = np.full(lat_vertices.shape[0], np.nan, dtype=np.float64)
    lat_max = np.full(lat_vertices.shape[0], np.nan, dtype=np.float64)
    if finite_vertices.any():
        lon_min[finite_vertices] = np.min(lon_vertices[finite_vertices], axis=1)
        lon_max[finite_vertices] = np.max(lon_vertices[finite_vertices], axis=1)
        lat_min[finite_vertices] = np.min(lat_vertices[finite_vertices], axis=1)
        lat_max[finite_vertices] = np.max(lat_vertices[finite_vertices], axis=1)
    valid_bbox = finite_vertices & (lat_max >= -90) & (lat_min <= 90) & (lon_max >= -180) & (lon_min <= 180)
    candidates = np.flatnonzero(valid_sif & valid_bbox)
    if candidates.size == 0:
        return "NO_VALID_SOURCE_FOOTPRINTS"

    possible_indices: list[int] = []
    for index in candidates:
        bbox = (float(lon_min[index]), float(lat_min[index]), float(lon_max[index]), float(lat_max[index]))
        if footprint.bounds_to_cell_keys(bbox) & target_keys:
            possible_indices.append(int(index))
    if not possible_indices:
        return "NO_BBOX_OVERLAP_WITH_SELECTED_SITES"

    context_by_id = {id(context): context for context in contexts}
    for index in possible_indices:
        source_bbox = (float(lon_min[index]), float(lat_min[index]), float(lon_max[index]), float(lat_max[index]))
        possible_context_ids: set[int] = set()
        for key in footprint.bounds_to_cell_keys(source_bbox):
            for context in context_keys.get(key, []):
                possible_context_ids.add(id(context))
        if not possible_context_ids:
            continue

        polygon = footprint.make_polygon_from_vertices(lon_vertices[index], lat_vertices[index])
        if polygon is None:
            for cid in possible_context_ids:
                context_by_id[cid]["bad_geometry_count"] += 1
            continue
        value = float(sif_values[index])
        if not math.isfinite(value) or value <= -9000:
            continue

        for cid in possible_context_ids:
            context = context_by_id[cid]
            if not footprint.bbox_intersects(source_bbox, context["geographic_bounds"]):
                continue
            context["candidate_count"] += 1
            context["geometry_fields_used"].add(f"{geom_lat_path} | {geom_lon_path}")
            try:
                polygon_projected = shapely_transform(context["transformer"].transform, polygon)
                if polygon_projected.is_empty:
                    context["bad_geometry_count"] += 1
                    continue
                if not polygon_projected.is_valid:
                    polygon_projected = polygon_projected.buffer(0)
                if polygon_projected.is_empty or not polygon_projected.is_valid:
                    context["bad_geometry_count"] += 1
                    continue
                template = context["template"]
                mask = rasterize(
                    [(polygon_projected, 1)],
                    out_shape=(template["height"], template["width"]),
                    transform=template["_transform_obj"],
                    fill=0,
                    all_touched=True,
                    dtype="uint8",
                ).astype(bool)
                ec_mask = mask & context["ec_mask"]
                n_ec = int(ec_mask.sum())
                if n_ec == 0:
                    context["no_spatial_intersection_count"] += 1
                    continue
                flat = np.flatnonzero(ec_mask.ravel())
                context["footprints"].append(
                    FootprintRecord(
                        footprint_id=f"{file_path.name}:{index}",
                        source_file=str(file_path),
                        source_index=int(index),
                        sif_value=value,
                        ec_flat_indices=flat,
                        n_ec_cells=n_ec,
                        single_probability_sum=float(context["probability_flat"][flat].sum(dtype=np.float64)),
                    )
                )
                context["source_files_used"].add(str(file_path))
            except Exception:
                context["bad_geometry_count"] += 1
                continue
    return "OK"


def stats_for_selected_footprints(context: dict[str, Any], selected_indices: list[int]) -> dict[str, Any]:
    n_pixels = int(context["template"]["height"]) * int(context["template"]["width"])
    sums = np.zeros(n_pixels, dtype=np.float64)
    counts = np.zeros(n_pixels, dtype=np.float32)
    footprints_list: list[FootprintRecord] = context["footprints"]
    for index in selected_indices:
        fp = footprints_list[index]
        sums[fp.ec_flat_indices] += fp.sif_value
        counts[fp.ec_flat_indices] += 1
    valid = counts > 0
    if not valid.any():
        return {
            "coverage_probability_fraction": 0.0,
            "coverage_pixel_fraction": 0.0,
            "weighted_sif": np.nan,
            "mean_sif": np.nan,
            "sd_sif": np.nan,
            "min_sif": np.nan,
            "max_sif": np.nan,
            "n_observed_ec_pixels": 0,
            "probability_sum_observed": 0.0,
            "support_mask": valid.reshape(context["probability"].shape),
            "sif_values_flat": np.array([], dtype=np.float64),
        }
    sif_flat = np.full(n_pixels, np.nan, dtype=np.float64)
    sif_flat[valid] = sums[valid] / counts[valid]
    probability = context["probability_flat"]
    weights = probability[valid]
    values = sif_flat[valid]
    probability_sum = float(weights.sum(dtype=np.float64))
    full_probability = float(context["probability_sum_full_EC"])
    weighted = float(np.sum(values * weights, dtype=np.float64) / probability_sum) if probability_sum > 0 else np.nan
    ec_pixels = int(context["n_EC_pixels"])
    return {
        "coverage_probability_fraction": probability_sum / full_probability if full_probability > 0 else np.nan,
        "coverage_pixel_fraction": int(valid.sum()) / ec_pixels if ec_pixels > 0 else np.nan,
        "weighted_sif": weighted,
        "mean_sif": float(np.mean(values)) if values.size else np.nan,
        "sd_sif": float(np.std(values, ddof=1)) if values.size > 1 else np.nan,
        "min_sif": float(np.min(values)) if values.size else np.nan,
        "max_sif": float(np.max(values)) if values.size else np.nan,
        "n_observed_ec_pixels": int(valid.sum()),
        "probability_sum_observed": probability_sum,
        "support_mask": valid.reshape(context["probability"].shape),
        "sif_values_flat": values,
    }


def candidate_subset_indices(context: dict[str, Any], target_coverage: float, scenario_key: str) -> tuple[list[int], dict[str, Any]]:
    footprints_list: list[FootprintRecord] = context["footprints"]
    n = len(footprints_list)
    if n <= 1:
        return [], {"subset_status": "IMPOSSIBLE_ONLY_ONE_FOOTPRINT"}
    rng = np.random.default_rng(stable_seed(context["row"]["original_case_ID"], scenario_key, RANDOM_SEED))
    candidates: list[list[int]] = []
    candidates.extend([[i] for i in range(n)])
    candidates.extend([[j for j in range(n) if j != i] for i in range(n)])
    by_prob = sorted(range(n), key=lambda i: footprints_list[i].single_probability_sum)
    candidates.append(by_prob[: max(1, min(n - 1, round(target_coverage * n)))])
    candidates.append(by_prob[-max(1, min(n - 1, round(target_coverage * n))) :])
    for _ in range(N_RANDOM_SUBSET_TRIALS):
        size = int(np.clip(round(rng.normal(loc=target_coverage * n, scale=max(1, n * 0.18))), 1, n - 1))
        candidates.append(sorted(rng.choice(n, size=size, replace=False).astype(int).tolist()))
    # Greedy random-order selections.
    for _ in range(18):
        order = rng.permutation(n).astype(int).tolist()
        chosen: list[int] = []
        best_cov = 0.0
        for idx in order:
            proposed = sorted(set(chosen + [idx]))
            stats_now = stats_for_selected_footprints(context, proposed)
            cov_now = safe_float(stats_now["coverage_probability_fraction"], 0.0)
            if cov_now <= target_coverage + 0.08 or abs(cov_now - target_coverage) < abs(best_cov - target_coverage):
                chosen = proposed
                best_cov = cov_now
            if best_cov >= target_coverage:
                break
        if chosen and len(chosen) < n:
            candidates.append(chosen)

    best_indices: list[int] = []
    best_stats: dict[str, Any] | None = None
    best_distance = float("inf")
    seen: set[tuple[int, ...]] = set()
    for candidate in candidates:
        key = tuple(sorted(set(int(i) for i in candidate)))
        if not key or len(key) >= n or key in seen:
            continue
        seen.add(key)
        stats_now = stats_for_selected_footprints(context, list(key))
        cov_now = safe_float(stats_now["coverage_probability_fraction"], np.nan)
        if not math.isfinite(cov_now) or cov_now <= 0 or cov_now >= FULL_COVERAGE_THRESHOLD:
            continue
        distance = abs(cov_now - target_coverage)
        if distance < best_distance:
            best_distance = distance
            best_indices = list(key)
            best_stats = stats_now
    if not best_indices or best_stats is None:
        return [], {"subset_status": "NO_NONFULL_SUBSET_FOUND"}
    best_stats["subset_status"] = "OK"
    best_stats["target_coverage_requested"] = float(target_coverage)
    best_stats["subset_abs_error_from_target"] = float(best_distance)
    return best_indices, best_stats


def empirical_coverage_targets(coverage: pd.DataFrame) -> list[tuple[str, float]]:
    vals = pd.to_numeric(
        coverage.loc[
            (coverage["PRODUCT"] == "OCO-3")
            & (coverage["coverage_probability_fraction"] > 0)
            & (coverage["coverage_probability_fraction"] < FULL_COVERAGE_THRESHOLD),
            "coverage_probability_fraction",
        ],
        errors="coerce",
    ).dropna()
    if vals.empty:
        return []
    quantiles = [0.05, 0.10, 0.25, 0.50, 0.75]
    return [(f"empirical_q{int(q*100):02d}", float(vals.quantile(q))) for q in quantiles]


