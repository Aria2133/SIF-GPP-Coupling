def select_truth_cases(coverage: pd.DataFrame, gosif_inventory: pd.DataFrame) -> pd.DataFrame:
    oco3 = coverage[
        (coverage["PRODUCT"] == "OCO-3")
        & (pd.to_numeric(coverage["coverage_probability_fraction"], errors="coerce") >= FULL_COVERAGE_THRESHOLD)
        & (coverage["status"] == "OK_OBSERVED_EC_SUPPORT")
    ].copy()
    gosif_cols = [
        "SITE_ID",
        "YYYYMM",
        "GOSIF_EC_weighted",
        "GOSIF_native_sd",
        "n_native_GOSIF_cells_intersecting_EC",
        "GOSIF_status",
    ]
    merged = oco3.merge(gosif_inventory[gosif_cols], on=["SITE_ID", "YYYYMM"], how="left")
    merged = merged[
        np.isfinite(pd.to_numeric(merged["GOSIF_EC_weighted"], errors="coerce"))
        & np.isfinite(pd.to_numeric(merged["target_observed_EC_weighted_SIF"], errors="coerce"))
    ].copy()
    merged["original_case_ID"] = (
        merged["SITE_ID"].astype(str) + "_" + merged["YYYYMM"].astype(str) + "_OCO3"
    )
    return merged.reset_index(drop=True)


def source_records_by_month(source_inventory: pd.DataFrame) -> dict[str, list[dict[str, Any]]]:
    oco3 = source_inventory[
        source_inventory["product"].astype(str).str.upper().isin(["OCO-3", "OCO3"])
        & (source_inventory["read_status"] == "OK")
    ].copy()
    out: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in oco3.to_dict("records"):
        yyyymm = str(record.get("detected_YYYYMM", ""))
        if len(yyyymm) == 6:
            record["product"] = "OCO-3"
            out[yyyymm].append(record)
    return dict(out)


