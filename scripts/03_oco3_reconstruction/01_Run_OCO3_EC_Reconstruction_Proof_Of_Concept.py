def metrics_dict(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    mask = np.isfinite(y_true) & np.isfinite(y_pred)
    y = np.asarray(y_true[mask], dtype=np.float64)
    p = np.asarray(y_pred[mask], dtype=np.float64)
    if y.size == 0:
        return {key: np.nan for key in ["n", "R2", "RMSE", "MAE", "Bias", "nRMSE", "Pearson_r", "Spearman_rho"]}
    rmse = math.sqrt(mean_squared_error(y, p))
    mae = mean_absolute_error(y, p)
    denom = float(np.nanmax(y) - np.nanmin(y)) if y.size > 1 else np.nan
    pearson = stats.pearsonr(y, p).statistic if y.size > 2 and np.std(y) > 0 and np.std(p) > 0 else np.nan
    spearman = stats.spearmanr(y, p).statistic if y.size > 2 and np.std(y) > 0 and np.std(p) > 0 else np.nan
    return {
        "n": int(y.size),
        "R2": float(r2_score(y, p)) if y.size > 1 else np.nan,
        "RMSE": float(rmse),
        "MAE": float(mae),
        "Bias": float(np.mean(p - y)),
        "nRMSE": float(rmse / denom) if math.isfinite(denom) and denom > 0 else np.nan,
        "Pearson_r": float(pearson) if math.isfinite(pearson) else np.nan,
        "Spearman_rho": float(spearman) if math.isfinite(spearman) else np.nan,
    }


def rf_uncertainty(pipe: Pipeline, x_test: pd.DataFrame, residual: bool = False) -> np.ndarray:
    try:
        transformed = pipe.named_steps["preprocess"].transform(x_test)
        forest = pipe.named_steps["model"]
        tree_preds = np.vstack([tree.predict(transformed) for tree in forest.estimators_])
        return tree_preds.std(axis=0)
    except Exception:
        return np.full(len(x_test), np.nan, dtype=np.float64)


def fold_predictions(
    train: pd.DataFrame,
    test: pd.DataFrame,
    validation_name: str,
    fold_id: str,
    selected_params_rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    y_train = train[TARGET_COLUMN].astype(float).to_numpy()
    y_test = test[TARGET_COLUMN].astype(float).to_numpy()
    rows: list[dict[str, Any]] = []

    def append_predictions(model_name: str, pred: np.ndarray, uncertainty: np.ndarray | None, notes: str) -> None:
        unc = uncertainty if uncertainty is not None else np.full(len(test), np.nan)
        for (_, rec), yhat, sig in zip(test.iterrows(), pred, unc):
            rows.append(
                {
                    "validation": validation_name,
                    "fold_id": fold_id,
                    "model": model_name,
                    "original_case_ID": rec["original_case_ID"],
                    "SITE_ID": rec["SITE_ID"],
                    "YYYYMM": rec["YYYYMM"],
                    "year": rec["year"],
                    "IGBP": rec.get("IGBP", ""),
                    "gap_scenario": rec["gap_scenario"],
                    "artificial_coverage_probability": rec["artificial_coverage_probability"],
                    "coverage_class": rec["coverage_class"],
                    "true_complete_OCO3_EC_SIF": rec[TARGET_COLUMN],
                    "prediction": float(yhat),
                    "prediction_uncertainty_exploratory": float(sig) if math.isfinite(float(sig)) else np.nan,
                    "partial_OCO3_EC_weighted_SIF": rec["partial_OCO3_EC_weighted_SIF"],
                    "GOSIF_EC_weighted": rec["GOSIF_EC_weighted"],
                    "error": float(yhat - rec[TARGET_COLUMN]),
                    "absolute_error": float(abs(yhat - rec[TARGET_COLUMN])),
                    "notes": notes,
                }
            )

    append_predictions(
        "Partial_observation_baseline",
        test["partial_OCO3_EC_weighted_SIF"].astype(float).to_numpy(),
        None,
        "No-learning baseline: complete estimate equals partial observed OCO-3 EC-weighted SIF.",
    )
    append_predictions(
        "GOSIF_raw_baseline",
        test["GOSIF_EC_weighted"].astype(float).to_numpy(),
        None,
        "No-learning baseline: raw scale-corrected GOSIF EC-weighted SIF.",
    )

    for model_name, spec in model_specs().items():
        estimator = clone(spec["estimator"])
        feature_cols = list(spec["features"])
        if spec.get("categorical"):
            feature_cols = feature_cols + CATEGORICAL_FEATURES
        x_train = train[feature_cols].copy()
        x_test = test[feature_cols].copy()
        selected_params_rows.append(
            {
                "validation": validation_name,
                "fold_id": fold_id,
                "model": model_name,
                "parameter_strategy": "fixed_modest_poc_parameters_no_test_tuning",
                "selected_parameters": str(estimator.get_params(deep=False)),
                "description": spec["description"],
            }
        )
        if spec["kind"] == "residual":
            residual_train = y_train - train["GOSIF_EC_weighted"].astype(float).to_numpy()
            estimator.fit(x_train, residual_train)
            residual_pred = estimator.predict(x_test)
