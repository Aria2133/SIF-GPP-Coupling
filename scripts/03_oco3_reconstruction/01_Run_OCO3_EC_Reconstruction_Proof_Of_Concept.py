def dataframe_markdown(frame: pd.DataFrame, max_rows: int = 25) -> str:
    if frame is None or frame.empty:
        return "_No rows._"
    shown = frame.head(max_rows)
    try:
        return shown.to_markdown(index=False)
    except Exception:
        return shown.to_string(index=False)


def write_pdf_from_markdown(markdown_path: Path, pdf_path: Path, figure_paths: list[Path] | None = None) -> None:
    styles = getSampleStyleSheet()
    normal = styles["BodyText"]
    heading = styles["Heading2"]
    title = styles["Title"]
    story: list[Any] = []
    text = markdown_path.read_text(encoding="utf-8")
    for raw_line in text.splitlines():
        line = raw_line.rstrip()
        if not line:
            story.append(Spacer(1, 0.08 * inch))
            continue
        if line.startswith("# "):
            story.append(Paragraph(line[2:], title))
        elif line.startswith("## "):
            story.append(Paragraph(line[3:], heading))
        elif line.startswith("|"):
            # Keep markdown tables readable without overengineering PDF conversion.
            story.append(Paragraph(line.replace("|", " | "), normal))
        else:
            story.append(Paragraph(line, normal))
    if figure_paths:
        story.append(PageBreak())
        story.append(Paragraph("Diagnostic figures", heading))
        for fig in figure_paths:
            if fig.exists():
                story.append(Paragraph(fig.name, normal))
                story.append(Image(native(fig), width=6.7 * inch, height=4.2 * inch))
                story.append(Spacer(1, 0.18 * inch))
    doc = SimpleDocTemplate(native(pdf_path), pagesize=A4, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    doc.build(story)


